/* departure -> ink (the binding data semantics) */
function depColor(dep) {
  if (dep === null || dep === undefined || Number.isNaN(dep)) return "#8B857A";
  if (dep >= 20) return "#1d4ed8";
  if (dep >= 0) return "#22c55e";
  if (dep >= -20) return "#eab308";
  if (dep >= -40) return "#f97316";
  return "#dc2626";
}

async function loadJSON(name) {
  const r = await fetch(`data/${name}.json`);
  if (!r.ok) throw new Error(`${name}.json: ${r.status}`);
  return r.json();
}

/* ── cartouche + ledger ──────────────────────────────────────────────── */
function renderMeta(meta) {
  const dep = meta.latest_monsoon_dep, mm = meta.latest_monsoon_mm;
  const sign = dep > 0 ? "+" : "";
  $("cart-dep").textContent = meta.latest_year;
  $("cart-pct").textContent = `${sign}${dep}%`;
  $("cart-dep2").textContent = `${sign}${dep}%`;
  $("cart-mm").textContent = `${mm.toLocaleString()} mm`;
  const n = meta.kpis.length;
  $("kpis").innerHTML = meta.kpis.map((k, i) =>
    `<div class="cell${i === n - 1 ? "" : ""}"><div class="k">${k.note}</div>` +
    `<div class="v">${k.v}</div><div class="n">${k.l}</div></div>`
  ).join("");
}

/* ── the ribbon: one plot, drawn from data, state in line form ───────── */
function drawRibbon(svg, national, mode) {
  const years = national.years;
  const vals = mode === "monsoon" ? national.monsoon : national.annual;
  const deps = national.monsoon_dep || [];
  const provisional = new Set(national.monsoon_provisional_years || []);
  const W = 1000, H = 300, pad = 6;
  const n = years.length;
  const bw = (W - pad * 2) / n;
  // monsoon mode reads departures around the normal line; annual mode reads
  // totals against the series' own floor and ceiling
  const MAXDEP = 35;
  const zero = mode === "monsoon" ? H / 2 : H - 26;
  const vvals = vals.filter((v) => v !== null && v !== undefined);
  const vmin = Math.min(...vvals), vmax = Math.max(...vvals);
  const vspan = Math.max(1, vmax - vmin);
  svg.innerHTML = "";
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);

  const reduce = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  for (let i = 0; i < n; i++) {
    const yr = years[i], v = vals[i];
    if (v === null || v === undefined) continue;
    const dep = mode === "monsoon" && deps[i] !== null && deps[i] !== undefined ? deps[i] : null;
    const isProv = mode === "monsoon" && provisional.has(yr);
    const frac = mode === "monsoon" && dep !== null
      ? Math.max(-1, Math.min(1, dep / MAXDEP))
      : (v - vmin) / vspan;
    const h = Math.max(2, Math.abs(frac) * (mode === "monsoon" ? (H / 2 - 14) : (H - 46)));
    const x = pad + i * bw;
    const bar = document.createElementNS(NS, "rect");
    bar.setAttribute("x", (x + 0.6).toFixed(2));
    bar.setAttribute("width", Math.max(1.4, bw - 1.4).toFixed(2));
    if (isProv) {
      // provisional reading: dashed outline, no fill — state in line form
      bar.setAttribute("y", zero - h);
      bar.setAttribute("height", h.toFixed(1));
      bar.setAttribute("fill", "none");
      bar.setAttribute("stroke", "#C0532E");
      bar.setAttribute("stroke-width", "1.4");
      bar.setAttribute("stroke-dasharray", "3 2.5");
    } else if (dep !== null) {
      bar.setAttribute("y", frac >= 0 ? zero - h : zero);
      bar.setAttribute("height", h.toFixed(1));
      bar.setAttribute("fill", depColor(dep));
      bar.setAttribute("opacity", "0.9");
    } else {
      // annual mode: totals from the floor; observed decade in salmon
      bar.setAttribute("y", (zero - h).toFixed(1));
      bar.setAttribute("height", h.toFixed(1));
      bar.setAttribute("fill", yr <= 2015 ? "#2E5E6E" : "#C0532E");
      bar.setAttribute("opacity", yr <= 2015 ? "0.78" : "0.95");
    }
    bar.setAttribute("class", "bar");
    if (!reduce) bar.style.animationDelay = `${Math.min(i * 6, 700)}ms`;
    if (!reduce && frac < 0) bar.style.transformOrigin = `${x + bw / 2}px ${zero}px`;
    svg.appendChild(bar);
  }

  // the reference rule, dashed: the normal (monsoon) or the series mean (annual)
  const ref = document.createElementNS(NS, "line");
  const refY = mode === "monsoon" ? zero
    : zero - ((vvals.reduce((a, b) => a + b, 0) / vvals.length) - vmin) / vspan * (H - 46);
  ref.setAttribute("x1", pad); ref.setAttribute("x2", W - pad);
  ref.setAttribute("y1", refY); ref.setAttribute("y2", refY);
  ref.setAttribute("stroke", "#1C1917"); ref.setAttribute("stroke-width", "1.1");
  ref.setAttribute("stroke-dasharray", "5 4");
  svg.appendChild(ref);
}

function drawHeroRibbon() {
  drawRibbon($("ribbon-hero"), NATIONAL, "monsoon");
  const prov = new Set(NATIONAL.monsoon_provisional_years || []);
  $("hero-stamp").hidden = !prov.has(META.latest_year);
  $("hero-gate").hidden = false;
}

function ribbonCaption(national) {
  const isMonsoon = state.series === "monsoon";
  const el = $("series-caption");
  if (isMonsoon) {
    const i = national.years.indexOf(2026);
    el.innerHTML = `Plate II — All-India Jun–Sep rainfall, 1901–2026. Salmon bars: observed decade; ` +
      `blue: pipeline years; the dashed 2026 outline is provisional (Jun–Sep only, ${national.monsoon[i]} mm, ` +
      `${national.monsoon_dep[i]}%). 2020 shows as a gap: its subdivision table fails machine validation.`;
  } else {
    el.innerHTML = `Plate II — All-India annual rainfall, 1901–2025 (blue: pipeline years; salmon: observed ` +
      `decade). 2026's annual total is not yet complete and is never mixed into this series.`;
  }
  for (const b of $("series-pills").children) {
    b.classList.toggle("active", b.dataset.s === state.series);
  }
}

function renderNational(national) {
  drawRibbon($("ribbon-national"), national, state.series);
  ribbonCaption(national);
  $("nat-stamp").hidden = !(state.series === "monsoon");
}

/* ── atlas (deck.gl, reskinned to the sheet) ─────────────────────────── */
let VALUES = null, deckInstance = null, polyData = [];
let NATIONAL = null, META = null;

function valueFor(division) {
  const bySeason = VALUES[state.season];
  if (!bySeason) return null;
  const byYear = bySeason[String(state.year)];
  if (!byYear) return null;
  const v = byYear[division];
  return v ? { mm: v[0], dep: v[1], obs: v[2] } : null;
}

function buildPolyData(subsJson) {
  polyData = [];
  for (const s of subsJson) {
    for (const ring of s.rings) {
      polyData.push({ name: s.division, region: s.region, polygon: ring });
    }
  }
}

function prismLayer() {
  return new window.deck.PolygonLayer({
    id: "prisms",
    data: polyData,
    getPolygon: (d) => d.polygon,
    getElevation: (d) => { const v = valueFor(d.name); return v && v.mm ? v.mm * 0.55 : 0; },
    elevationScale: 1,
    extruded: true,
    getFillColor: (d) => {
      const v = valueFor(d.name);
      const c = depColor(v ? v.dep : null);
      const r = parseInt(c.slice(1, 3), 16), g = parseInt(c.slice(3, 5), 16), b = parseInt(c.slice(5, 7), 16);
      return [r, g, b, 200];
    },
    getLineColor: [28, 25, 23],
    lineWidthMinPixels: 1,
    pickable: true,
    autoHighlight: true,
    highlightColor: [192, 83, 46, 110],
    updateTriggers: {
      getElevation: [state.season, state.year],
      getFillColor: [state.season, state.year],
    },
    transitions: { getElevation: 220, getFillColor: 220 },
  });
}

function renderMapNote() {
  const note = $("map-note");
  const bySeason = VALUES[state.season];
  const hasYear = bySeason && bySeason[String(state.year)];
  if (state.year === 2026) {
    note.hidden = false;
    note.innerHTML = `2026 subdivision values are not published yet — the all-India reading on Plate I is the live figure.`;
  } else if (state.year === 2020) {
    note.hidden = false;
    note.innerHTML = `2020's subdivision table fails machine validation (IMD "real time" values) and is excluded rather than shown wrong.`;
  } else if (!hasYear) {
    note.hidden = false;
    note.innerHTML = `No subdivision data for ${state.year} in this season.`;
  } else {
    note.hidden = true;
  }
  $("atlas-title").textContent = `${state.season} ${state.year}`;
}

function redraw() {
  $("year-readout").textContent = state.year;
  if (deckInstance) deckInstance.setProps({ layers: [prismLayer()] });
  renderMapNote();
}

function initDeck() {
  deckInstance = new window.deck.Deck({
    canvas: $("deck-canvas"),
    initialViewState: { longitude: 79.6, latitude: 22.4, zoom: 3.75, pitch: 52, bearing: -12, minZoom: 2.5, maxZoom: 9 },
    controller: true,
    getTooltip: (info) => {
      if (!info.object) return null;
      const d = info.object, v = valueFor(d.name);
      const tag = v ? (v.obs ? "observed IMD" : "pipeline layer") : "";
      const body = v
        ? `<div style="font-size:15px;font-weight:700;margin:3px 0">${v.mm == null ? "—" : v.mm.toLocaleString()} mm</div>
           <div>% dep: <b>${v.dep == null ? "—" : (v.dep > 0 ? "+" : "") + v.dep + "%"}</b></div>`
        : `<div style="opacity:.75">no data for this year</div>`;
      return { html:
        `<div style="background:#FBF8F1;border:1.5px solid #1C1917;border-radius:2px;padding:10px 13px;max-width:260px;color:#1C1917;font-family:'Public Sans',sans-serif">
           <div style="font-weight:700;font-size:14px">${d.name}</div>${body}
           <div style="margin-top:5px;font-size:11px;color:#4A443C">${d.region} · <i>${tag}</i></div>
         </div>`, style: { backgroundColor: "transparent" } };
    },
    layers: [prismLayer()],
  });
}

/* ── controls ────────────────────────────────────────────────────────── */
function renderSeasonPills(seasons) {
  const el = $("season-pills");
  el.innerHTML = "";
  for (const s of seasons) {
    const b = document.createElement("button");
    b.className = "pill" + (s === state.season ? " active" : "");
    b.textContent = s;
    b.setAttribute("role", "tab");
    b.onclick = () => { state.season = s; renderSeasonPills(seasons); redraw(); };
    el.appendChild(b);
  }
}

function bindSlider() {
  const sl = $("year-slider");
  sl.value = state.year;
  sl.oninput = () => { state.year = +sl.value; redraw(); };
  $("play-btn").onclick = togglePlay;
}

function togglePlay() {
  const btn = $("play-btn");
  state.playing = !state.playing;
  $("play-path").setAttribute("d", state.playing
    ? "M3.5 2.5h3v11h-3zM9.5 2.5h3v11h-3z" : "M4 2.5v11l9-5.5-9-5.5Z");
  btn.classList.toggle("playing", state.playing);
  if (state.playing) {
    if (state.year >= 2026) { state.year = 1901; }
    state.timer = setInterval(() => {
      state.year = state.year >= 2026 ? 1901 : state.year + 1;
      $("year-slider").value = state.year;
      redraw();
    }, 260);
  } else {
    clearInterval(state.timer);
  }
}

function bindSeriesPills() {
  const el = $("series-pills");
  el.innerHTML = "";
  for (const [label, key] of [["Jun–Sep monsoon", "monsoon"], ["Annual", "annual"]]) {
    const b = document.createElement("button");
    b.className = "pill" + (key === state.series ? " active" : "");
    b.dataset.s = key; b.textContent = label; b.setAttribute("role", "tab");
    b.onclick = () => { state.series = key; renderNational(NATIONAL); };
    el.appendChild(b);
  }
}

