/* VARSA static edition — deck.gl prism atlas + Plotly national chart.
   Data: ../data/*.json, regenerated by scripts/build_site_data.py. */

const GREY = [120, 130, 145, 190];
const state = { season: "Monsoon", year: 2025, playing: false, timer: null, series: "monsoon" };

const $ = (id) => document.getElementById(id);

function depColor(dep) {
  if (dep === null || dep === undefined || Number.isNaN(dep)) return GREY;
  if (dep >= 20) return [29, 78, 216, 190];
  if (dep >= 0) return [34, 197, 94, 190];
  if (dep >= -20) return [234, 179, 8, 190];
  if (dep >= -40) return [249, 115, 22, 190];
  return [220, 38, 38, 200];
}

async function loadJSON(name) {
  const r = await fetch(`data/${name}.json`);
  if (!r.ok) throw new Error(`${name}.json: ${r.status}`);
  return r.json();
}

/* ── header: banner + KPIs ─────────────────────────────────────────────── */
function renderMeta(meta) {
  const b = $("live-banner"), dep = meta.latest_monsoon_dep;
  b.hidden = false;
  if (dep >= 0) b.classList.add("good");
  else if (dep > -10) b.classList.add("mild");
  $("banner-title").textContent =
    `${meta.latest_year} monsoon in progress — ${meta.latest_monsoon_mm.toLocaleString()} mm Jun–Sep ` +
    `(${dep > 0 ? "+" : ""}${dep}% of normal)`;
  $("kpis").innerHTML = meta.kpis.map((k) =>
    `<div class="kpi"><div class="v">${k.v}</div><div class="l">${k.l}</div><div class="n">${k.note}</div></div>`
  ).join("");
}

/* ── 3D prism atlas ────────────────────────────────────────────────────── */
let SUBS = null, VALUES = null, deckInstance = null, polyData = [];

function valueFor(division) {
  const bySeason = VALUES[state.season];
  if (!bySeason) return null;
  const byYear = bySeason[String(state.year)];
  if (!byYear) return null;
  const v = byYear[division];
  return v ? { mm: v[0], dep: v[1], obs: v[2] } : null;
}

function buildPolyData(subsJson) {
  polyData = [];
  for (const s of subsJson) {
    for (const ring of s.rings) {
      polyData.push({ name: s.division, region: s.region, polygon: ring });
    }
  }
}

function prismLayer() {
  return new window.deck.PolygonLayer({
    id: "prisms",
    data: polyData,
    getPolygon: (d) => d.polygon,
    getElevation: (d) => { const v = valueFor(d.name); return v && v.mm ? v.mm * 0.55 : 0; },
    elevationScale: 1,
    extruded: true,
    getFillColor: (d) => { const v = valueFor(d.name); return depColor(v ? v.dep : null); },
    getLineColor: [10, 16, 28],
    lineWidthMinPixels: 1,
    pickable: true,
    autoHighlight: true,
    highlightColor: [255, 213, 122, 90],
    updateTriggers: {
      getElevation: [state.season, state.year],
      getFillColor: [state.season, state.year],
    },
    transitions: { getElevation: 220, getFillColor: 220 },
  });
}

function renderMapNote() {
  const note = $("map-note");
  const bySeason = VALUES[state.season];
  const hasYear = bySeason && bySeason[String(state.year)];
  if (state.year === 2026) {
    note.hidden = false;
    note.innerHTML = `2026 subdivision values are not published yet — all-India monsoon so far shown in the banner and chart below.`;
  } else if (state.year === 2020 && state.year > 2015) {
    note.hidden = false;
    note.innerHTML = `2020's subdivision table fails machine validation (IMD "real time" values) and is excluded rather than shown wrong.`;
  } else if (!hasYear) {
    note.hidden = false;
    note.innerHTML = `No subdivision data for ${state.year} in this season.`;
  } else {
    note.hidden = true;
  }
}

function redraw() {
  $("year-readout").textContent = state.year;
  if (deckInstance) deckInstance.setProps({ layers: [prismLayer()] });
  renderMapNote();
}

function initDeck() {
  deckInstance = new window.deck.Deck({
    canvas: $("deck-canvas"),
    initialViewState: { longitude: 79.6, latitude: 22.4, zoom: 3.75, pitch: 52, bearing: -12, minZoom: 2.5, maxZoom: 9 },
    controller: true,
    getTooltip: (info) => {
      if (!info.object) return null;
      const d = info.object, v = valueFor(d.name);
      const layerTag = v ? (v.obs ? '<span class="layer-tag" style="color:#7ee2a8">observed IMD</span>'
                                  : '<span class="layer-tag">pipeline layer</span>') : "";
      const body = v
        ? `<div style="font-size:15px;font-weight:700;margin-bottom:3px">${v.mm == null ? "—" : v.mm.toLocaleString()} mm</div>
           <div>% dep: <b style="color:${v.dep >= 0 ? "#7ee2a8" : "#ffB4a6"}">${v.dep == null ? "—" : (v.dep > 0 ? "+" : "") + v.dep + "%"}</b></div>`
        : `<div style="opacity:.75">no data for this year</div>`;
      return { html:
        `<div style="background:rgba(11,20,40,.94);border:1px solid #1E3558;border-radius:10px;padding:10px 13px;max-width:260px">
           <div style="font-weight:700;font-size:14px;margin-bottom:4px">${d.name}</div>${body}
           <div style="margin-top:5px;font-size:11px">${d.region} · ${layerTag}</div>
         </div>`, style: { backgroundColor: "transparent" } };
    },
    layers: [prismLayer()],
  });
}

/* ── controls ──────────────────────────────────────────────────────────── */
function renderSeasonPills(seasons) {
  const el = $("season-pills");
  el.innerHTML = "";
  for (const s of seasons) {
    const b = document.createElement("button");
    b.className = "pill" + (s === state.season ? " active" : "");
    b.textContent = s;
    b.onclick = () => { state.season = s; renderSeasonPills(seasons); redraw(); };
    el.appendChild(b);
  }
}

function bindSlider() {
  const sl = $("year-slider");
  sl.value = state.year;
  sl.oninput = () => { state.year = +sl.value; redraw(); };
  $("play-btn").onclick = togglePlay;
}

function togglePlay() {
  const btn = $("play-btn");
  state.playing = !state.playing;
  btn.textContent = state.playing ? "❚❚" : "▶";
  btn.classList.toggle("playing", state.playing);
  if (state.playing) {
    if (state.year >= 2026) { state.year = 1901; }
    state.timer = setInterval(() => {
      state.year = state.year >= 2026 ? 1901 : state.year + 1;
      $("year-slider").value = state.year;
      redraw();
    }, 260);
  } else {
    clearInterval(state.timer);
  }
}

/* ── national chart ────────────────────────────────────────────────────── */
function renderNational(national) {
  const isMonsoon = state.series === "monsoon";
  const y = national.years;
  const vals = isMonsoon ? national.monsoon : national.annual;
  const dep = national.monsoon_dep;
  const clean = vals.map((v) => (v === null ? null : v));
  const mean = clean.filter((v) => v !== null && y[clean.indexOf(v)] <= 2015);
  // mean of the 1901-2015 baseline
  let sum = 0, n = 0;
  y.forEach((yr, i) => { if (yr <= 2015 && clean[i] !== null) { sum += clean[i]; n++; } });
  const base = sum / n;
  const colors = y.map((yr, i) => {
    if (clean[i] === null) return "rgba(120,130,145,.35)";
    if (!isMonsoon) return yr <= 2015 ? "rgba(147,197,253,.75)" : "rgba(224,165,38,.9)";
    const d = dep[i];
    if (d === null || d === undefined) return "rgba(147,197,253,.75)";
    if (d >= 20) return "rgba(29,78,216,.9)";
    if (d >= 0) return "rgba(34,197,94,.85)";
    if (d >= -20) return "rgba(234,179,8,.85)";
    if (d >= -40) return "rgba(249,115,22,.9)";
    return "rgba(220,38,38,.95)";
  });

  const traces = [{
    type: "bar", x: y, y: clean, marker: { color: colors },
    hovertemplate: "<b>%{x}</b>: %{y:,.0f} mm<extra></extra>",
  }, {
    type: "scatter", mode: "lines", x: [y[0], y[y.length - 1]], y: [base, base],
    line: { color: "#7ee2a8", dash: "dash", width: 1.5 },
    hoverinfo: "skip", showlegend: false,
  }];

  Plotly.newPlot("national-chart", traces, {
    margin: { t: 10, b: 34, l: 52, r: 12 },
    paper_bgcolor: "rgba(0,0,0,0)", plot_bgcolor: "rgba(0,0,0,0)",
    font: { family: "Plus Jakarta Sans", color: "#C9D6EA", size: 11 },
    xaxis: { title: "", gridcolor: "rgba(30,53,88,.6)", range: [1899, 2028] },
    yaxis: { title: isMonsoon ? "Jun–Sep rainfall (mm)" : "Annual rainfall (mm)", gridcolor: "rgba(30,53,88,.6)" },
    showlegend: false,
    config: { displayModeBar: false, responsive: true },
  }, { displayModeBar: false, responsive: true });

  $("series-caption").innerHTML = isMonsoon
    ? `All-India Jun–Sep rainfall, 1901–2026 (bars coloured by % departure; dashed line = 1901–2015 mean ${Math.round(base)} mm). ` +
      `2026 in progress: ${national.monsoon[national.years.indexOf(2026)]} mm (${national.monsoon_dep[national.years.indexOf(2026)]}%), Jun–Sep only — provisional; compare with full seasons in prior years.`
    : `All-India annual rainfall, 1901–2025 (2026 annual total not yet complete — never mixed in). Blue = historical record, amber = the recovered observed decade; dashed line = 1901–2015 mean ${Math.round(base)} mm.`;

  for (const b of $("series-pills").children) {
    b.classList.toggle("active", b.dataset.s === state.series);
  }
}

function bindSeriesPills(national) {
  const el = $("series-pills");
  el.innerHTML = "";
  for (const [label, key] of [["Jun–Sep monsoon", "monsoon"], ["Annual", "annual"]]) {
    const b = document.createElement("button");
    b.className = "pill" + (key === state.series ? " active" : "");
    b.dataset.s = key;
    b.textContent = label;
    b.onclick = () => { state.series = key; renderNational(national); };
    el.appendChild(b);
  }
}

/* ── boot ──────────────────────────────────────────────────────────────── */
(async () => {
  const [meta, subs, values, national] = await Promise.all([
    loadJSON("meta"), loadJSON("subdivisions"), loadJSON("values"), loadJSON("national"),
  ]);
  SUBS = subs; VALUES = values;
  renderMeta(meta);
  buildPolyData(subs);
  renderSeasonPills(meta.seasons);
  bindSlider();
  initDeck();
  redraw();
  bindSeriesPills(national);
  renderNational(national);
})().catch((e) => {
  document.body.insertAdjacentHTML("afterbegin",
    `<div style="margin:20px;padding:14px;border:1px solid #dc2626;border-radius:12px;` +
    `background:rgba(220,38,38,.1)">Failed to load data: ${e}</div>`);
});
